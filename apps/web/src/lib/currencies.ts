const COMMON = ['EUR', 'USD', 'GBP', 'ILS'];

/** Select options, common ones first: "EUR · Euro". An unlisted code (e.g. from older data) is added. */
export function currencyOptions(current?: string): { value: string; label: string }[] {
  const names = new Intl.DisplayNames(['en'], { type: 'currency' });
  const rest = CODES.filter((c) => !COMMON.includes(c));
  const all = [...COMMON, ...rest];
  if (current && !all.includes(current)) all.push(current);
  return all.map((code) => ({ value: code, label: `${code} · ${names.of(code) ?? code}` }));
}
